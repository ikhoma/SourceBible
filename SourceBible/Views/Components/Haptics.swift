//
// ЧОМУ ОДНЕ МІСЦЕ. До цього хаптика жила рівно в одному рядку (`VerseTextView`,
// тап по слову) і була `.medium` — надто важка для найчастішої дії в застосунку.
// Розсипати виклики генераторів по в'юшках і VM означало б повторити історію
// радіусів і зазорів: числа розповзаються, і за пів року ніхто не скаже, чому
// в одному місці medium, а в сусідньому light.
//
// ПРИНЦИП (HIG): хаптика підкреслює ЗМІСТ дії, а не факт дотику. Тому назви
// методів семантичні — call-site читається як намір, а не як сила вібрації.
//
// ⛔ СВІДОМО БЕЗ ХАПТИКИ: зміна глави (чеврон/свайп) і перемикання перекладу.
// Глави гортають постійно під час читання — вібрація там швидко стає шумом,
// а не сигналом. Перемикання перекладу вже має власний зворотний звʼязок:
// закриття шіта й перемальований текст.
//
// Системні генератори самі поважають налаштування «Системна хаптика» на пристрої,
// тож окремого перемикача в застосунку не потрібно.

import UIKit

@MainActor
enum Haptics {

    /// Рух по дискретних елементах: тап по слову, чеврони по віршах і словах,
    /// зняття highlight. Найлегший фідбек — саме тому, що трапляється найчастіше.
    static func selectionChanged() {
        UISelectionFeedbackGenerator().selectionChanged()
    }

    /// Легкий перехід стану: відкриття Study Mode, перемикання закладки,
    /// перехід по перехресному посиланню (і назад по стеку).
    /// Щось сталося, але сліду в даних майже немає.
    ///
    /// Чому крос-реф тут, а не в `selectionChanged()`: чеврони — це крок на
    /// сусідній вірш, а перехресне — стрибок в іншу книгу. Більша дія має
    /// відчуватись відчутніше, інакше вийде навпаки.
    static func lightTransition() {
        UIImpactFeedbackGenerator(style: .light).impactOccurred()
    }

    /// Змістовна дія з видимим слідом у даних: поставлений highlight.
    /// Навмисно відчутніша за решту — це єдиний спосіб відрізнити «я створив»
    /// від «я просто рухаюсь».
    static func meaningfulAction() {
        UIImpactFeedbackGenerator(style: .medium).impactOccurred()
    }
}
